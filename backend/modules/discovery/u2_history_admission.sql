-- Discovery owns search admission order. Library consumes only narrow evidence.
CREATE TABLE discovery.owner_admission (
  account_id uuid PRIMARY KEY, sequence bigint NOT NULL DEFAULT 0 CHECK(sequence>=0)
);
CREATE TABLE discovery.admission (
  execution_id uuid PRIMARY KEY, account_id uuid NOT NULL, sequence bigint NOT NULL,
  authority_revision uuid NOT NULL, query_hash text NOT NULL CHECK(length(query_hash)=64),
  accepted_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(account_id,sequence)
);
ALTER TABLE discovery.execution ADD COLUMN completion_sequence bigint GENERATED BY DEFAULT AS IDENTITY;
GRANT SELECT,INSERT,UPDATE ON discovery.owner_admission TO docsuri_discovery;
GRANT SELECT,INSERT ON discovery.admission TO docsuri_discovery;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA discovery TO docsuri_discovery;
CREATE FUNCTION discovery.history_checkpoint(p_account uuid,p_session uuid)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE result bigint;
BEGIN
  PERFORM accounts.guard_session(p_account,p_session,'account-control');
  INSERT INTO discovery.owner_admission(account_id) VALUES(p_account) ON CONFLICT DO NOTHING;
  SELECT sequence INTO result FROM discovery.owner_admission WHERE account_id=p_account FOR UPDATE;
  RETURN result;
END $$;
CREATE FUNCTION discovery.history_fact(p_account uuid,p_session uuid,p_execution uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE current_revision uuid; result jsonb;
BEGIN
  current_revision:=accounts.guard_session(p_account,p_session,'account-control');
  SELECT jsonb_build_object('id',e.id,'query',e.query,'completedAt',e.completed_at,
    'admissionSequence',a.sequence,'completionSequence',e.completion_sequence) INTO result
    FROM discovery.execution e JOIN discovery.admission a ON e.id=a.execution_id
    WHERE e.id=p_execution AND e.account_id=p_account AND a.account_id=p_account
      AND a.authority_revision=current_revision AND a.query_hash=e.query_hash;
  RETURN result;
END $$;
REVOKE ALL ON FUNCTION discovery.history_checkpoint(uuid,uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION discovery.history_fact(uuid,uuid,uuid) FROM PUBLIC;
GRANT USAGE ON SCHEMA discovery TO docsuri_library;
GRANT EXECUTE ON FUNCTION discovery.history_checkpoint(uuid,uuid),discovery.history_fact(uuid,uuid,uuid) TO docsuri_library;
