def manifest_now(ctx: InstallContext, *, version: int | None = None) -> Manifest:
    """The arrangement as it stands: every rendered rule and configuration file in place,
    every runtime and fixed program, each runtime's configuration files, `pg_hba.conf`
    and `pg_ident.conf`, and the loaded anchor's rules. A runtime's pinned name holding
    something other than a regular file keeps its entry with `UNREAD_DIGEST`
    (`_runtime_entry`)."""
    from docsuri_ops.isolation_macos import rules_digest

    from . import runtimes

    entries: list[Entry] = []
    prefix = ctx.paths.prefix
    rendered = [item for item in render.render(ctx.paths, ctx.accounts, operator=ctx.operator,
                                               tunnel_name=ctx.tunnel_name)]
    for item in rendered:
        owner = None if item.owner == "root" else ctx.uid(item.owner)
        if prefix in item.target.parents:
            # Under the prefix, `postgres/data` is the database account's, and it holds
            # `postgresql.conf` (the rule files are in the root-owned `postgres-rules`, read
            # the same way): each rendered file under the prefix is digested only
            # through the no-link walk, as a regular file with one name (your answer of
            # 2026-11-10, "Fix both and sweep the rest"), and nothing is raised from
            # `apply`'s `finally`. A refused or absent file keeps its entry with
            # `UNREAD_DIGEST`, which matches no file, so the isolation check's `files`
            # item answers `file-differs` until an apply reads it again: leaving it out
            # would take it out of the check (the re-review of 2026-11-10).
            # The walk's digest is recorded only when it is the digest of the bytes the
            # installer rendered: the database account could otherwise rewrite
            # `postgresql.conf` (one name, a regular file) between phase
            # 3's write and this record, and its bytes would become the baseline the
            # isolation check compares against (the batch-7 review). Anything else is
            # `UNREAD_DIGEST`, so `files` answers `file-differs` until an apply puts the
            # rendered bytes back.
            entries.append(Entry(manifest_path(ctx.paths, item.target), item.kind,
                                 _rendered_digest(prefix, item), None, owner))
        elif item.target.is_file() and not item.target.is_symlink():
            entries.append(entry_for(ctx.paths, item.target, item.kind, owner_uid=owner))
    for pin in runtimes.RUNTIMES:
        folder = ctx.paths.runtimes / pin.folder
        found = [_runtime_entry(ctx, folder / program, "program", folder)
                 for program in pin.programs]
        found += [_runtime_entry(ctx, folder / config_file, "config", None)
                  for config_file in pin.config_files]
        entries += [entry for entry in found if entry is not None]
    for name in render.FIXED_PROGRAMS:
        path = ctx.paths.release_bin / name
        if path.is_file():
            entries.append(entry_for(ctx.paths, path, "program", root=ctx.paths.release))
    hba_digest, ident_digest = (
        _rule_file_digest(prefix, rendered, ctx.paths.postgres_rules / name)
        for name in ("pg_hba.conf", "pg_ident.conf"))
    rules = ctx.tools.anchor_rules()
    return Manifest(version or render.arrangement_version(), tuple(entries), hba_digest,
                    None if rules is None else rules_digest(rules),
                    pg_ident_sha256=ident_digest)


def _runtime_entry(ctx: InstallContext, path: Path, kind: str,
                   root: Path | None) -> Entry | None:
    """One runtime's program (kind `program`, with the runtime's folder as its root) or
    configuration file (kind `config`, no root and no owner, so the isolation check
    expects root). A regular file is digested as built; an absent path has no entry.
    Anything else at the name, a link, a FIFO or a folder, keeps its entry with
    `UNREAD_DIGEST`, which matches no file, so the isolation check answers
    `program-custody` or `file-differs` until an apply finds a regular file there again,
    and nothing is raised from `apply`'s `finally`."""
    try:
        return entry_for(ctx.paths, path, kind, root=root)
    except FileNotFoundError:
        return None
    except (OSError, ManifestRefused):
        return Entry(manifest_path(ctx.paths, path), kind, UNREAD_DIGEST,
                     None if root is None else manifest_path(ctx.paths, root), None)


def _rule_file_digest(prefix, rendered: list[render.Rendered], target: Path) -> str | None:
    """One PostgreSQL rule file's recorded digest (`pgHbaSha256`, `pgIdentSha256`): the
    rendered bytes' digest when the file in place holds them, otherwise None, which the
    isolation check's `database` item counts as a difference."""
    item = next((item for item in rendered if item.target == target), None)
    digest = None if item is None else _rendered_digest(prefix, item)
    return None if digest == UNREAD_DIGEST else digest


def _rendered_digest(prefix, item: render.Rendered) -> str:
    """The no-link walk's digest of `item.target` when it equals the digest of the bytes
    the installer rendered for it; `UNREAD_DIGEST` when the walk refused the file, found
    none, or found other bytes."""
    digest = safe_fs.sha256_at(prefix, item.target)
    if digest is None or digest != hashlib.sha256(item.content).hexdigest():
        return UNREAD_DIGEST
    return digest


def record_manifest(ctx: InstallContext) -> bool:
    """Write the manifest when the arrangement differs from the recorded one (so a
    second run that changes nothing writes nothing)."""
    current = manifest_now(ctx)
    recorded = read_manifest(ctx.paths)
    if recorded is not None and recorded.as_dict() | {"writtenAt": None} == (
        current.as_dict() | {"writtenAt": None}
    ):
        return False
    write_manifest(ctx.paths, current, clock=ctx.clock, owner_uid=ctx.root_uid)
    return True


class Installer:
    def __init__(self, ctx: InstallContext, phases=PHASES):
        self.ctx, self.phases = ctx, phases

    def plan(self) -> Outcome:
        """Every change of every phase, with its difference; nothing is applied."""
        outcome = Outcome("plan")
        for phase in self.phases:
            changes = phase.changes(self.ctx)
            outcome.phases.append({"phase": phase.name, "changes": len(changes)})
            outcome.changes += [change.describe() for change in changes]
        return outcome

    def apply(self) -> Outcome:
        """The phases in order; each checks its own result before the next starts."""
        outcome = Outcome("apply")
        try:
            for phase in self.phases:
                changes = phase.changes(self.ctx)
                for change in changes:
                    change.apply()
                    self.ctx.log.write(phase.name, change.action, "applied",
                                       target=_loggable(change.target))
                    outcome.changes.append(change.describe())
                phase.verify(self.ctx)
                self.ctx.log.write(phase.name, "verify", "passed", count=len(changes))
                outcome.phases.append({"phase": phase.name, "changes": len(changes),
                                       "verified": True})
        except (PhaseFailed, NotConfirmed, safe_fs.PathRefused) as failure:
            # A descriptor walk's refusal (your answer of 2026-11-10, "Fix both and sweep
            # the rest") stops the phase with its fixed key, as a phase's own check does.
            reason = getattr(failure, "reason", None) or getattr(failure, "item", "failed")
            outcome.failed, outcome.reason = phase.name, reason
            self.ctx.log.write(phase.name, "verify", "failed", reason=_key(reason))
        finally:
            record_manifest(self.ctx)
        return outcome


def _key(reason: str) -> str:
    cleaned = "".join(c if c.isalnum() or c in ".:_-" else "-" for c in reason.lower())
    return cleaned[:80] or "failed"


def _loggable(target: str) -> str:
    cleaned = "".join(c if c.isalnum() or c in "/._ -" else "-" for c in target)
    return cleaned[:240] or "target"


