def driver_config(ctx: InstallContext, actor: str) -> dict:
    """The arrangement driver's configuration for one actor's effects folder; paths
    only, never a secret."""
    value = {"kind": "arrangement", "production": True, "actor": actor,
             "databasePort": 15432, "v1Stores": dict(ctx.v1_stores)}
    if actor == "scheduler":
        value["schedulerCredentials"] = str(ctx.paths.scheduler_credentials)
    if actor == "operator":
        # Your login account, through whose own in-person grant the release command (root)
        # reaches the backup agent's backup and ledger copy (your decision of 2026-10-26,
        # "Through your login"); the agent refuses root.
        value["operatorLogin"] = ctx.operator
    if actor == "operator" and ctx.v1_sources:
        # The addresses the production migration platform reads v1 at, and no other
        # (the person's decision of 2026-10-24); checked when the platform loads them.
        value["v1Sources"] = dict(ctx.v1_sources)
    if ctx.v1_checkout is not None:
        value["v1Checkout"] = str(ctx.v1_checkout)
        value["v1Runtime"] = [str(ctx.v1_checkout / "backend" / ".venv" / "bin" / "python")]
    return value


class FoldersDatabasePhase:
    name = "folders-and-database"

    def changes(self, ctx: InstallContext) -> list[Change]:
        found: list[Change | None] = []
        for relative, owner, mode in FOLDERS:
            found.append(folder_change(ctx, self.name, _prefixed(ctx, relative), owner, mode))
        for path in timemachine.missing(ctx.tools):
            found.append(Change(self.name, "time-machine", path, "included -> excluded",
                                lambda path=path: timemachine.exclude(ctx.tools, path)))
        if not ctx.database.initialised():
            found.append(Change(self.name, "initdb", str(ctx.paths.postgres_data),
                                "absent -> initialised, SCRAM and loopback only",
                                ctx.database.initdb))
        # `postgresql.conf` into the data folder; `pg_hba.conf` and `pg_ident.conf` into the
        # root-owned rules folder (a FOLDERS entry, set above), before the job starts.
        for item in render.render_postgres(ctx.paths, ctx.accounts):
            found.append(file_change(ctx, self.name, item))
        found.append(folder_change(ctx, self.name, ctx.paths.postgres_data / "log",
                                   "database", 0o700))
        plist = next(item for item in render.render_launch_jobs(ctx.paths, ctx.accounts)
                     if item.target.name == "org.docsuri.v2.postgres.plist")
        found.append(file_change(ctx, self.name, plist))
        if ctx.tools.job_state("org.docsuri.v2.postgres") is None:
            found.append(Change(self.name, "job", "org.docsuri.v2.postgres", "absent -> started",
                                lambda: ctx.tools.bootstrap(plist.target)))
        missing = [key for key, present in holders(ctx).items() if not present]
        if missing or not all(ctx.database.identities().values()):
            found.append(Change(
                self.name, "database", "docsuri_v2 and docsuri_v2_platform",
                "missing " + (",".join(missing) or "databases") + " -> roles, databases and "
                "each secret in its holder",
                lambda: self._database(ctx)))
        drifted = store_login_drift(ctx)
        if drifted:
            # An existing install whose store logins are unbound, or whose reader login
            # still holds the runtime role (review findings, Minor, R16 and R17).
            found.append(Change(self.name, "store-logins", "docsuri_v2_platform",
                                f"{','.join(drifted)} unbound or runtime -> each login bound "
                                "to its actor, the reader out of the runtime role",
                                lambda: bind_existing_logins(ctx)))
        manifest = ctx.paths.profile / "environment.json"
        if not manifest.exists():
            found.append(Change(self.name, "profile", str(manifest),
                                "absent -> rehearsal, maintainer-only",
                                lambda: self._profile(ctx)))
        for actor in ("operator", "scheduler"):
            config = json.dumps(driver_config(ctx, actor), sort_keys=True).encode()
            found.append(file_change(ctx, self.name, render.Rendered(
                ctx.paths.effects / actor / "driver.json", config, 0o600, actor, "config")))
        if not ctx.paths.healthchecks.exists():
            found.append(Change(self.name, "healthchecks", str(ctx.paths.healthchecks),
                                "absent -> three check addresses", lambda: self._checks(ctx)))
        if ctx.migrate is not None and migrated_chain(ctx) != chain_digest(ctx.source):
            found.append(Change(
                self.name, "migrate", "docsuri_v2_template and docsuri_v2_platform",
                "chain not applied -> the release's migrate as the service account",
                lambda: self._migrate(ctx)))
        return [change for change in found if change is not None]

    def _database(self, ctx: InstallContext) -> None:
        installed = install_database(ctx)
        provision_platform(ctx, installed["passwords"])

    def _profile(self, ctx: InstallContext) -> None:
        value = profile_manifest(ctx)
        payload = json.dumps(value, sort_keys=True).encode()
        write_file(ctx, ctx.paths.profile / "environment.json", payload, 0o600, "service")
        # The first rehearsal database's name, no secret, for `cutover begin` (the operator
        # cannot read the service account's profile).
        write_file(ctx, ctx.paths.control / FIRST_REHEARSAL,
                   json.dumps({"database": value["rehearsalDatabase"]}).encode(), 0o644, "root")

    def _migrate(self, ctx: InstallContext) -> None:
        """Phase 3's end (your decision of 2026-10-24): the linked release's
        `docsuri-production-tool migrate` as the service account, with the operator login
        from the System keychain. A current database that does not exist yet is reported
        `absent`; the template and the platform database come onto the chain. The chain
        it applied is recorded root-owned, so a second run changes nothing."""
        result = ctx.migrate(ctx)
        if result.get("failed") or not isinstance(result.get("template"), dict):
            raise PhaseFailed("migrate-failed")
        ctx.log.write(self.name, "migrate", "done",
                      reason="database-absent" if result.get("state") == "absent"
                      else "database-migrated")
