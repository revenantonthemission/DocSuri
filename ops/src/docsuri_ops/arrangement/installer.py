"""The installer (U8 plan Step 37; infrastructure-specification § 4, Workflow 20, D8).

`docsuri-installer plan | apply | verify | change-password`, run in person as root
(`sudo -k`):

- **plan** lists every change of the seven phases, each with its difference, and
  changes nothing;
- **apply** runs the phases in order, each checking its own result before the next
  starts; a phase that fails stops the installer there, and a second run changes nothing;
- **verify** runs the installation's own checks (`verify.py`) and the isolation check;
- **change-password** changes one holder's production passwords together with its
  roles' SCRAM verifiers (`password_change.py`; U8 plan Step 136, L2-7), reading
  `{"login": <holder>}` on standard input.

Every step that needs your eyes or a login is a checklist item it waits on, every
password is generated by root straight into its holder (`keychain.py`), and the
installation log records each step's name and outcome, never a secret. After a run the
arrangement manifest (`control/arrangement-manifest.json`) records the digest of every
file in place, whichever way the run ended.

This module holds phase 3 (folders and the database) and phases 6 and 7 beside the
runner; `phases.py` holds the shared changes and phases 1, 2, 4 and 5.
"""

