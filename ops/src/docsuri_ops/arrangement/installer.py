class ProductionDatabase:
    """v2's instance as the installer reaches it: `initdb` and `psql` as the database
    account over the private socket (the superuser has no password), and the
    PlatformControl store's provisioner over loopback with SCRAM."""

    def __init__(self, ctx: InstallContext):
        self.ctx = ctx

    def _bin(self, name: str) -> str:
        return str(self.ctx.paths.postgres_runtime / "bin" / name)

    def _as_database(self, argv: list[str], **options) -> bytes:
        uid = self.ctx.accounts.database.uid
        return self.ctx.tools.run(argv, user=uid, group=uid, **options)

    def initialised(self) -> bool:
        return (self.ctx.paths.postgres_data / "PG_VERSION").exists()

    def initdb(self) -> None:
        self._as_database([self._bin("initdb"), "-D", str(self.ctx.paths.postgres_data),
                           "-U", render.SUPERUSER, "--auth-local=peer", "--auth-host=reject",
                           "-E", "UTF8", "--locale=C", "--no-instructions"])

    def _psql(self, *arguments: str) -> list[str]:
        return [self._bin("psql"), "-X", "-h", str(self.ctx.paths.postgres_socket), "-p",
                "15432", "-U", render.SUPERUSER, "-d", "postgres", *arguments]

    def ready(self) -> bool:
        try:
            self._as_database([self._bin("pg_isready"), "-h", str(self.ctx.paths.postgres_socket),
                               "-p", "15432", "-U", render.SUPERUSER, "-d", "postgres"])
        except Exception:  # noqa: BLE001 - not ready is the answer
            return False
        return True

    def run_script(self, script: str) -> None:
        """The script on psql's standard input only (it holds generated passwords)."""
        self._as_database(self._psql("-q", "-f", "-"), input=script.encode())

    def login_check(self, role: str, password: str, *, port: int = 15432) -> bool:
        """Whether `role` logs in with `password` over loopback with SCRAM (pg_hba admits
        every role there that way): one connection to `postgres`, answering whether
        `current_user` is the role. A refused login answers False."""
        import psycopg

        try:
            with psycopg.connect(host="127.0.0.1", port=port, dbname="postgres", user=role,
                                 password=password, require_auth="scram-sha-256",
                                 connect_timeout=5) as conn:
                row = conn.execute("SELECT current_user").fetchone()
        except psycopg.OperationalError:
            return False
        return row is not None and row[0] == role

    def identities(self) -> dict:
        """Whether `docsuri_v2` and the store exist."""
        query = ("SELECT (SELECT count(*) FROM pg_database WHERE datname='docsuri_v2')::text"
                 "||','||(SELECT count(*) FROM pg_database WHERE "
                 "datname='docsuri_v2_platform')::text")
        try:
            answer = self._as_database(self._psql("-At", "-c", query))
        except Exception:  # noqa: BLE001 - not answering: neither exists yet
            return {"production": False, "platform": False}
        production, _, platform = answer.decode().strip().partition(",")
        return {"production": production == "1", "platform": platform == "1"}

    def store(self, password: str):
        from docsuri_ops.platform_control.store import DatabaseTarget
        from docsuri_ops.production_tool import PLATFORM_PROVISIONER
        from docsuri_ops.u8_platform.platform_profile import scram_store

        return scram_store(DatabaseTarget("127.0.0.1", 15432, PRODUCTION_DATABASES.platform),
                           PLATFORM_PROVISIONER, password)  # SCRAM demanded (NFR3.3)


def holders(ctx: InstallContext) -> dict[str, bool]:
    """Which secret holders already exist; an existing holder's password is never
    changed here."""
    tools, paths = ctx.tools, ctx.paths
    return {
        "owners": (paths.profile / "owner-credentials.json").exists(),
        "scheduler": paths.scheduler_credentials.exists(),
        "backupAgent": (paths.backup_agent / "v2-login").exists(),
        "operator": keychain.present(tools, "operator"),
        "restore": keychain.present(tools, "restore"),
        "platformOperator": keychain.present(tools, "platform"),
        "provisioner": (paths.control / "platform-provisioner.json").exists(),
        "reader": (paths.profile / "platform-reader.json").exists(),
    }


def install_database(ctx: InstallContext) -> dict:
    """Every missing holder's password generated by root from 32 random bytes, the
    roles and databases created or adjusted by the installation script (an existing
    holder's role keeps its password), then each new password written straight into its
    holder: a 0600 file of the holder's account, or the System keychain."""
    from docsuri_ops.production_tool import OWNERS, installation_script

    present = holders(ctx)

    def fresh(key: str) -> str | None:
        return None if present[key] else ctx.generate().decode()

    passwords = {
        "owners": {owner: None for owner in OWNERS} if present["owners"]
        else {owner: ctx.generate().decode() for owner in OWNERS},
        "scheduler": fresh("scheduler"), "backupAgent": fresh("backupAgent"),
        "operator": fresh("operator"), "restore": fresh("restore"),
        "platform": {"provisioner": fresh("provisioner"), "operator": fresh("platformOperator"),
                     "scheduler": fresh("scheduler"), "reader": fresh("reader")},
    }
    ctx.database.run_script(installation_script(ctx.source, run_id=ctx.run_id,
                                                passwords=passwords))
    written = []
    service, backup = ctx.accounts.service, ctx.accounts.backup
    if not present["owners"]:
        keychain.write_secret_file(ctx.paths.profile / "owner-credentials.json",
                                   {"runId": ctx.run_id, "roles": passwords["owners"]},
                                   uid=service.uid, gid=service.uid, base=ctx.paths.prefix,
                                   tools=ctx.tools)
        written.append("owners")
    if not present["backupAgent"]:
        # The backup account's folder: created new relative to its descriptor and given
        # through the file's own descriptor before it is closed (your answer of
        # 2026-11-10, "Fix both and sweep the rest"), never chowned by path afterwards.
        keychain.write_secret_bytes(ctx.paths.backup_agent / "v2-login",
                                    passwords["backupAgent"].encode(), uid=backup.uid,
                                    gid=backup.uid, base=ctx.paths.prefix, tools=ctx.tools)
        written.append("backupAgent")
    for key, login in (("operator", "operator"), ("restore", "restore"),
                       ("platformOperator", "platform")):
        value = passwords["platform"]["operator"] if key == "platformOperator" else passwords[key]
        if value is not None:
            keychain.store_login(ctx.tools, login, value.encode())
            written.append(key)
    if not present["provisioner"]:
        keychain.write_secret_file(ctx.paths.control / "platform-provisioner.json",
                                   {"password": passwords["platform"]["provisioner"]},
                                   uid=ctx.root_uid, gid=0, base=ctx.paths.prefix,
                                   tools=ctx.tools)
        written.append("provisioner")
    ctx.log.write("folders-and-database", "database-roles", "done", count=len(written))
    return {"written": written, "passwords": passwords}


def platform_grants(ctx: InstallContext, targets: list[str]) -> dict:
    """The production store's authorities: the operator's routine and destructive grants
    (in person), the scheduler's standing grants and the service account's reader."""
    from docsuri_ops.u8_platform.u8_protocols import SCHEDULER_GRANTS, load_revision

    revision = load_revision(ctx.source / "ops/src/docsuri_ops/platform_control/inventory.json")

    def names(authority_class: str) -> list[str]:
        return [p.name for p in revision.u8 if p.authority_class == authority_class]

    operator, scheduler = ctx.operator, ctx.accounts.scheduler.name
    grants = {
        "operatorRoutine": (operator, targets, names("routine"), "routine"),
        "operatorDestructive": (operator, targets, names("destructive-release"),
                                "destructive-release"),
        "serviceReader": (ctx.accounts.service.name, targets,
                          ["inspectEvidence", "readReceipt"], "evidence-reader"),
    }
    for name, (scope, operations, authority_class) in SCHEDULER_GRANTS.items():
        grants[name] = (scheduler, list(scope), list(operations), authority_class)
    return grants


def provision_platform(ctx: InstallContext, passwords: dict) -> dict:
    """PlatformControl's targets and authorities in `docsuri_v2_platform`, then the
    scheduler's credentials file and the service account's reader file. The authority
    identities, which are no secret, go to `control/platform-authorities.json`."""
    import uuid

    from docsuri_ops.production_tool import PLATFORM_LOGINS
    from docsuri_ops.u8_platform.platform_profile import PRODUCTION_LABELS
    from docsuri_ops.u8_platform.u8_protocols import (
        SCHEDULER_GRANTS,
        bind_store_logins,
        load_revision,
    )

    authorities_path = ctx.paths.control / "platform-authorities.json"
    provisioner = json.loads((ctx.paths.control / "platform-provisioner.json").read_bytes())
    store = ctx.database.store(provisioner["password"])
    if authorities_path.exists():
        recorded = json.loads(authorities_path.read_bytes())
        # Each store login bound to its actor, an install made before the binding included
        # (your decision of 2026-10-26, "Bind each login to its actor").
        bind_store_logins(store, PLATFORM_LOGINS, recorded["actors"])
        return recorded
    revision = load_revision(ctx.source / "ops/src/docsuri_ops/platform_control/inventory.json")
    targets = sorted({target for protocol in revision.u8 for target in protocol.targets}
                     | set(PRODUCTION_LABELS) | {"backup-volume"})
    for target in targets:
        store.provision_target(target)
    authorities = {}
    for name, (actor, scope, operations, authority_class) in platform_grants(
        ctx, targets
    ).items():
        identity = str(uuid.uuid4())
        store.provision_authority(authority_id=identity, actor=actor, scope=scope,
                                  operations=operations, authority_class=authority_class,
                                  binding={"production": ctx.run_id, "grant": name})
        authorities[name] = identity
    platform = passwords["platform"]
    scheduler, service = ctx.accounts.scheduler, ctx.accounts.service
    if platform["scheduler"] is not None and not ctx.paths.scheduler_credentials.exists():
        keychain.write_secret_file(ctx.paths.scheduler_credentials, {
            "database": {"user": DATABASE_ROLES.scheduler, "password": passwords["scheduler"]},
            "platform": {"user": PLATFORM_LOGINS["scheduler"], "password": platform["scheduler"]},
            "actor": scheduler.name,
            "authorities": {name: authorities[name] for name in SCHEDULER_GRANTS},
        }, uid=scheduler.uid, gid=scheduler.uid, base=ctx.paths.prefix, tools=ctx.tools)
    if platform["reader"] is not None:
        keychain.write_secret_file(ctx.paths.profile / "platform-reader.json", {
            "authorityId": authorities["serviceReader"], "actor": service.name,
            "password": platform["reader"],
        }, uid=service.uid, gid=service.uid, base=ctx.paths.prefix, tools=ctx.tools)
    value = {"actors": {"operator": ctx.operator, "scheduler": scheduler.name,
                        "service": service.name},
             "authorities": authorities}
    bind_store_logins(store, PLATFORM_LOGINS, value["actors"])
    write_file(ctx, authorities_path, json.dumps(value, sort_keys=True).encode(), 0o644, "root")
    ctx.log.write("folders-and-database", "platform-authorities", "done",
                  count=len(authorities))
    return value


def _provisioner_store(ctx: InstallContext):
    provisioner = json.loads((ctx.paths.control / "platform-provisioner.json").read_bytes())
    return ctx.database.store(provisioner["password"])


def store_login_drift(ctx: InstallContext) -> list[str]:
    """Each production store login read back as the provisioner and compared with the
    binding the installation makes (`u8_protocols.login_binding_drift`; review findings,
    Minor, R16 and R17): the kinds whose login is unbound, bound otherwise, or (the
    reader's) still a member of the runtime role. Empty when nothing is recorded yet
    (the first install binds at provisioning)."""
    from docsuri_ops.production_tool import PLATFORM_LOGINS
    from docsuri_ops.u8_platform.u8_protocols import login_binding_drift

    authorities_path = ctx.paths.control / "platform-authorities.json"
    if not authorities_path.exists() or not (
            ctx.paths.control / "platform-provisioner.json").exists():
        return []
    recorded = json.loads(authorities_path.read_bytes())
    return login_binding_drift(_provisioner_store(ctx), PLATFORM_LOGINS, recorded["actors"])


def bind_existing_logins(ctx: InstallContext) -> list[str]:
    """Phase 3 on an existing install (review findings, Minor, R16 and R17): each store
    login bound to its recorded actor (`bind_store_logins`, idempotent), and the reader
    login taken out of the runtime role and into the reader role when it still holds the
    runtime role. Answers the kinds that drifted before."""
    from docsuri_ops.platform_control.errors import ControlError
    from docsuri_ops.production_tool import PLATFORM_LOGINS, reader_role_script
    from docsuri_ops.u8_platform.u8_protocols import bind_store_logins

    drift = store_login_drift(ctx)
    if not drift:
        return []
    recorded = json.loads((ctx.paths.control / "platform-authorities.json").read_bytes())
    store = _provisioner_store(ctx)
    for kind in drift:
        try:
            bind_store_logins(store, {kind: PLATFORM_LOGINS[kind]}, recorded["actors"])
        except ControlError:
            # A login is never rebound: one bound to another actor is a store someone
            # else provisioned, which no apply repairs.
            raise PhaseFailed(f"store-login-bound-elsewhere:{kind}") from None
    if "reader" in drift:
        ctx.database.run_script(reader_role_script())
    ctx.log.write("folders-and-database", "store-logins", "done", count=len(drift))
    return drift


def scheduler_grant_drift(ctx: InstallContext) -> list[str]:
    """The scheduler's grants in `docsuri_v2_platform`, read as the provisioner and
    compared with `SCHEDULER_GRANTS` (`u8_protocols.grant_drift`; review finding, Minor,
    R15): an install provisioned before a grant changed fails `verify` instead of
    passing with a routine grant that still holds a restore."""
    from docsuri_ops.u8_platform.u8_protocols import grant_drift

    recorded = json.loads((ctx.paths.control / "platform-authorities.json").read_bytes())
    provisioner = json.loads((ctx.paths.control / "platform-provisioner.json").read_bytes())
    store = ctx.database.store(provisioner["password"])
    return grant_drift(store, recorded["authorities"], recorded["actors"]["scheduler"])


