class ServiceControlFailed(Exception):
    """The operator tool's service control did not settle as applied."""


# One in-person service control asks for your password three times, each through
# `sudo -k`: the PlatformControl login's release (`docsuri-credential-release platform`),
# the ledger copy (`docsuri-ledger copy`) and the fixed program (`docsuri-service-stop` or
# `-start`). The bound allows each prompt up to three minutes of your time, plus the run
# itself (the review's fix of 2026-10-26: the tools' 60 s default could end the run while
# you typed, leaving the operator tool running on). The third prompt's real bound is
# shorter (review finding, Minor, R13): the fixed program runs inside the bounded effect,
# whose `platform.service.control` deadline (120 s, inventory.json) covers that prompt
# and the program together, and the driver ends the program itself at a bound below
# that deadline (`drivers.arrangement.program_bound`; review finding, Minor, R16), so an
# answer later than that fails the effect whatever `SERVICE_CONTROL_SECONDS` allows and
# writes no stop record; the control then fails, and running it again binds a new
# receipt.
PASSWORD_PROMPTS = 3
PROMPT_SECONDS = 180
SERVICE_CONTROL_SECONDS = PASSWORD_PROMPTS * PROMPT_SECONDS + 120


def operator_service(ctx: InstallContext) -> Callable[[str, str], dict]:
    """The operator tool's in-person service control (the person's decision of
    2026-10-25, "Add an in-person stop command"), run as your login account from the
    linked release: `echo '{}' | <release>/.venv/bin/python -I -m docsuri_ops.u8_platform
    service <stop|start> <label> --production`. Its PlatformControl login and each effect
    go through `sudo -k`, so you authenticate in person (`PASSWORD_PROMPTS` prompts, within
    `SERVICE_CONTROL_SECONDS`); it answers the bound receipt. Before it binds, the operator
    tool reconciles any earlier unresolved service control of that label
    (`u8_protocols.reconcile_unresolved`)."""

    def control(action: str, label: str) -> dict:
        argv = ["/usr/bin/sudo", "-u", ctx.operator, str(ctx.paths.release / ".venv/bin/python"),
                "-I", "-m", "docsuri_ops.u8_platform", "service", action, label,
                "--production"]
        try:
            answer = json.loads(ctx.tools.run(argv, input=b"{}",
                                              seconds=SERVICE_CONTROL_SECONDS)
                                .decode().splitlines()[-1])
        except Exception as error:  # noqa: BLE001 - any failure is the control's failure
            raise ServiceControlFailed(action) from error
        if not answer.get("ok"):
            raise ServiceControlFailed(action)
        return answer["result"]

    return control


def installer_control_key_start(ctx: InstallContext, *, run=None, service=None) -> dict:
    """Phase 7's keyring start: v2's three roles stopped through the operator tool's
    in-person service control (`operator_service`; each stop's receipt bound in
    PlatformControl's store before its stop record is written), the linked release's
    `docsuri-production-tool control-key-start` as the service account, then every role
    that was stopped started again the same way, whatever the word answered. The
    installation log records each stop's and start's bound operation.

    A role that does not start again fails the keyring start (`service-start-failed:
    <label>`), whatever the word answered, and the label is kept in `control/
    keyring-start-unstarted.json`, so the phase fails, `verify` fails, and the next
    `apply` starts it (`RestartCheckPhase`): a v2 role is never left down behind a
    succeeded word (review finding, Major, R10)."""
    from docsuri_ops.production_tool import V2_ROLES, invoke
    from docsuri_ops.production_tool import Refused as ToolRefused

    control_service = service or operator_service(ctx)

    def control(action: str, label: str) -> None:
        receipt = control_service(action, label)
        ctx.log.write("restart-and-check", f"service-{action}", "applied", target=label,
                      item=str(receipt["operationId"]))

    stopped: list[str] = []
    unstarted: list[str] = []
    try:
        for label in V2_ROLES:
            control("stop", label)
            stopped.append(label)
        result = invoke("control-key-start", {}, run=run,
                        program=str(ctx.paths.release_bin / "docsuri-production-tool"))["result"]
    except ToolRefused as refused:
        result = {"failed": {"reason": refused.reason}}
    except ServiceControlFailed:
        result = {"failed": {"reason": "service-control-failed"}}
    finally:
        for label in stopped:
            try:
                control("start", label)
            except ServiceControlFailed:
                ctx.log.write("restart-and-check", "service-start", "failed", target=label)
                unstarted.append(label)
        record_unstarted(ctx, unstarted)
    if unstarted:
        return {"failed": {"reason": f"service-start-failed:{unstarted[0]}",
                           "unstarted": list(unstarted)}}
    return result


UNSTARTED = "keyring-start-unstarted.json"


def unstarted_roles(ctx: InstallContext) -> list[str]:
    """The v2 roles the keyring start stopped and could not start again, from
    `control/keyring-start-unstarted.json` (written by the installer, as root); none when
    it is absent, and the phase fails when it is not in its form."""
    from docsuri_ops.production_tool import V2_ROLES

    path = ctx.paths.control / UNSTARTED
    try:
        value = json.loads(path.read_bytes())
    except FileNotFoundError:
        return []
    except (OSError, ValueError):
        raise PhaseFailed("keyring-start-record-unreadable") from None
    labels = value.get("labels") if isinstance(value, dict) else None
    if not isinstance(labels, list) or not labels or not set(labels) <= set(V2_ROLES):
        raise PhaseFailed("keyring-start-record-unreadable")
    return [str(label) for label in labels]


def record_unstarted(ctx: InstallContext, labels: list[str]) -> None:
    """Keeps the roles left stopped (or removes the record once every one started)."""
    path = ctx.paths.control / UNSTARTED
    if not labels:
        if path.exists() or path.is_symlink():
            path.unlink()
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    pending = path.with_name(path.name + ".pending")
    if pending.exists() or pending.is_symlink():
        pending.unlink()
    descriptor = os.open(pending, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
    try:
        os.write(descriptor, json.dumps({"labels": sorted(set(labels))}).encode())
        os.fsync(descriptor)
    finally:
        os.close(descriptor)
    os.replace(pending, path)


def start_unstarted(ctx: InstallContext, *, service=None) -> None:
    """The next `apply`'s change: each role the keyring start left stopped, started
    through the operator tool's in-person service control; the record keeps what is still
    down, and the phase fails while anything is."""
    control_service = service or operator_service(ctx)
    still = []
    for label in unstarted_roles(ctx):
        try:
            receipt = control_service("start", label)
        except ServiceControlFailed:
            ctx.log.write("restart-and-check", "service-start", "failed", target=label)
            still.append(label)
            continue
        ctx.log.write("restart-and-check", "service-start", "applied", target=label,
                      item=str(receipt["operationId"]))
    record_unstarted(ctx, still)
    if still:
        raise PhaseFailed(f"service-start-failed:{still[0]}")


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    if any(name.startswith(("PYTHON", "DYLD_", "LD_")) for name in os.environ):
        print(json.dumps({"ok": False, "reason": "environment-refused"}))
        return 2
    parser = argparse.ArgumentParser(prog="docsuri-installer")
    parser.add_argument("word", choices=WORDS)
    try:
        args = parser.parse_args(arguments)
    except SystemExit:
        print(json.dumps({"ok": False, "reason": "word-refused"}))
        return 2
    if os.geteuid() != 0:
        print(json.dumps({"ok": False, "reason": "root-required"}))
        return 2
    settings = json.loads((ArrangementPaths().control / "installation.json").read_bytes())

    def clock() -> dt.datetime:
        return dt.datetime.now(dt.UTC)

    ctx = production_context(settings, clock=clock)
    if args.word == "change-password":
        return _change_password(ctx)
    installer = Installer(ctx)
    if args.word == "plan":
        result = installer.plan().as_dict()
    elif args.word == "apply":
        result = installer.apply().as_dict()
    else:
        from . import verify

        result = verified(verify.run_checks(ctx))
    print(json.dumps({"ok": result.get("failed") is None, **result}, sort_keys=True))
    return 0 if result.get("failed") is None else 1


def verified(checks: list[dict]) -> dict:
    """The `verify` word's result: every check with its outcome and, when any did not
    pass, their names under `failed`, so the word is ok only when every check passed and
    exits 1 otherwise."""
    failed = [item["check"] for item in checks if not item["passed"]]
    return {"checks": checks, **({"failed": failed} if failed else {})}


def _change_password(ctx: InstallContext) -> int:
    """The `change-password` word (U8 plan Step 136(f)): standard input, the process's
    environment (for the account sudo authenticated), the arrangement's paths, the
    production context and production's ledger view, read as root as the release command
    reads it."""
    from docsuri_ops.production_wiring import LedgerClient

    from . import password_change

    paths = ArrangementPaths()
    result, code = password_change.run_change_password(
        sys.stdin.buffer, os.environ, paths=paths, context=ctx,
        ledger=LedgerClient(via="in-person", paths=paths))
    print(json.dumps(result, sort_keys=True))
    return code
