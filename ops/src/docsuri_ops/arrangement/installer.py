def chain_digest(source: Path) -> str:
    """The composed chain the release holds: each file of U1's amendments and the chain,
    with its digest, and the platform store's files (the inventory and U8's store
    amendment, `platform_profile.STORE_FILES`), as one SHA-256. A change to the amendment
    alone changes it, so phase 3 migrates again (the person's decision of 2026-10-25,
    "After the move, same build")."""
    import hashlib

    from backend.u8_migrations import U1_AMENDMENTS, migrations

    from docsuri_ops.u8_platform.platform_profile import STORE_FILES

    digest = hashlib.sha256()
    files = [file for _, file in (*U1_AMENDMENTS, *migrations())]
    files.extend(STORE_FILES)
    for file in files:
        digest.update(file.encode() + b"\0" + hashlib.sha256((source / file).read_bytes())
                      .hexdigest().encode() + b"\n")
    return digest.hexdigest()


def migrated_chain(ctx) -> str | None:
    """The chain digest phase 3's migrate last applied, or None."""
    try:
        value = json.loads((ctx.paths.control / MIGRATED_CHAIN).read_bytes())
    except (OSError, ValueError):
        return None
    return value.get("chainDigest") if isinstance(value, dict) else None


