"""A production password changed in person, together with its roles' SCRAM verifiers
(U8 plan Step 136; security-design § 6.1, "Changing one"; D8, NFR3.2; L2-7).

`echo '{"login": "<holder>"}' | sudo -k /Library/DocSuri/release/ops/bin/docsuri-installer
change-password` changes every password one holder keeps, over a closed set of eight
holders and their nineteen roles (`HOLDERS`). For each run, in this order:

1. the arrangement marker is held for the whole change (reason `password-change`);
2. the holder's precondition is read: v2 stopped, no scheduled backup or verification,
   or no release command, recovery or migration run under way;
3. the holder is checked in place (a 0600 single-name file of its account, reached by the
   no-link walk from the root-owned prefix, or its System keychain item);
4. one new secret per role is generated by root, each with its SCRAM verifier computed
   here, so the server never receives a password;
5. a file holder's new bytes go into a pending file beside it;
6. the roles' verifiers are set in one transaction;
7. the holder is rewritten (a rename, or the keychain item replaced);
8. the holder is read back as root and compared with the new values;
9. each role logs in with its new value;
10. for the scheduler only, the standing job is restarted (`launchctl kickstart -k`).

Nothing changes before step 6. Each outcome writes one line to the root-owned audit
record `control/password-changes.jsonl` and one to the installation log; neither line,
nor the answer, ever holds a value, digest or length of a secret.
"""

from __future__ import annotations

import base64
import contextlib
import copy
import hashlib
import hmac
import json
import os
import re
import secrets
import stat
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from docsuri_ops.production_tool import OWNERS, PLATFORM_LOGINS, PLATFORM_PROVISIONER

from . import keychain, manifest, safe_fs
from .checklist import InstallationLog
from .paths import DATABASE_ROLES, ArrangementPaths

WORD = "change-password"
PHASE = "password-change"
REASON = "password-change"
AUDIT_RECORD = "password-changes.jsonl"
PENDING_SUFFIX = ".docsuri-pending"
STANDING_JOB = "system/org.docsuri.v2.standing"
MAX_INPUT = 4 * 1024
MAX_HOLDER = 64 * 1024
SALT_BYTES = 16
ITERATIONS = 4096
_SECRET = re.compile(r"[0-9a-f]{64}")
_PASSWORD = re.compile(r"[0-9a-f]{32,128}")
_B64 = "[A-Za-z0-9+/]"
_VERIFIER = re.compile(rf"SCRAM-SHA-256\$[1-9][0-9]{{3,6}}:{_B64}{{22}}==\${_B64}{{43}}=:"
                       rf"{_B64}{{43}}=")
SCHEDULED_OPERATIONS = ("backup.create", "restore.verify")


class Refused(Exception):
    """A change refused or stopped; the message (and `reason`) is a fixed key."""

    def __init__(self, reason: str, *, failed: bool = False):
        super().__init__(reason)
        self.reason, self.failed = reason, failed


@dataclass(frozen=True)
class Holder:
    """One holder of production passwords: its roles, where it keeps their passwords
    (`kind` `file`, `raw` or `keychain`), each role's field in a file holder, the account
    that owns it, what it needs first and what the change means afterwards."""

    key: str
    roles: tuple[str, ...]
    kind: str
    location: Callable[[ArrangementPaths], Path] | str
    fields: tuple[tuple[str, ...], ...]
    account: str
    precondition: str
    consequence: str


def _holders() -> dict[str, Holder]:
    owners = tuple(f"docsuri_{owner}" for owner in OWNERS)
    return {holder.key: holder for holder in (
        Holder("owners", owners, "file", lambda p: p.profile / "owner-credentials.json",
               tuple(("roles", owner) for owner in OWNERS), "service", "v2-stopped",
               "v2-reads-them-at-its-next-start"),
        Holder("platform-reader", (PLATFORM_LOGINS["reader"],), "file",
               lambda p: p.profile / "platform-reader.json", (("password",),), "service",
               "v2-stopped", "v2-reads-them-at-its-next-start"),
        Holder("scheduler", (DATABASE_ROLES.scheduler, PLATFORM_LOGINS["scheduler"]), "file",
               lambda p: p.scheduler_credentials,
               (("database", "password"), ("platform", "password")), "scheduler",
               "scheduled-work", "standing-job-restarted"),
        Holder("backup-agent", (DATABASE_ROLES.backup_agent,), "raw",
               lambda p: p.backup_agent / "v2-login", ((),), "backup", "scheduled-work",
               "read-at-the-agents-next-run"),
        Holder("operator", (DATABASE_ROLES.operator,), "keychain", "operator", ((),), "root",
               "in-person-logins", "read-at-the-next-in-person-use"),
        Holder("restore", (DATABASE_ROLES.restore,), "keychain", "restore", ((),), "root",
               "in-person-logins", "read-at-the-next-in-person-use"),
        Holder("platform-operator", (PLATFORM_LOGINS["operator"],), "keychain", "platform",
               ((),), "root", "in-person-logins", "read-at-the-next-in-person-use"),
        Holder("provisioner", (PLATFORM_PROVISIONER,), "file",
               lambda p: p.control / "platform-provisioner.json", (("password",),), "root",
               "none", "read-at-the-next-installer-run"),
    )}


HOLDERS = _holders()
SCHEDULED = ("scheduler", "backup-agent")
KEYCHAIN_LOGINS = ("operator", "restore", "platform-operator")


# --- the verifier and the script ---------------------------------------------------------------


def _b64(value: bytes) -> str:
    return base64.b64encode(value).decode("ascii")


def scram_sha256_verifier(password: str, *, salt: bytes, iterations: int = ITERATIONS) -> str:
    """PostgreSQL's stored SCRAM-SHA-256 form of `password` (RFC 5802, RFC 7677):
    `SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>`, each part base64. A
    generated password is hexadecimal, which SASLprep leaves as it is."""
    if not _PASSWORD.fullmatch(password) or len(salt) != SALT_BYTES:
        raise ValueError("verifier input outside its form")
    salted = hashlib.pbkdf2_hmac("sha256", password.encode("ascii"), salt, iterations)
    client_key = hmac.new(salted, b"Client Key", hashlib.sha256).digest()
    stored_key = hashlib.sha256(client_key).digest()
    server_key = hmac.new(salted, b"Server Key", hashlib.sha256).digest()
    return f"SCRAM-SHA-256${iterations}:{_b64(salt)}${_b64(stored_key)}:{_b64(server_key)}"


def alter_roles_script(holder: str, verifiers: dict[str, str]) -> str:
    """One transaction setting each of the holder's roles to its new verifier. It holds no
    password, so none reaches the server, psql or any log. A role outside the holder's
    set, a missing role, or a verifier outside its form refuses before anything runs."""
    known = HOLDERS.get(holder)
    if known is None or set(verifiers) != set(known.roles) or not all(
            isinstance(value, str) and _VERIFIER.fullmatch(value)
            for value in verifiers.values()):
        raise Refused("verifier-outside-its-form")
    lines = ["\\set ON_ERROR_STOP on", "\\connect postgres", "BEGIN;"]
    lines += [f"ALTER ROLE {role} PASSWORD '{verifiers[role]}';" for role in known.roles]
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


# --- the ledger reader ---------------------------------------------------------------------------


def work_under_way(ledger, login: str) -> str | None:
    """The refusal key of work that would read this holder's logins mid-flight, read from
    a ledger view's `records(kind)`; None when nothing is under way."""
    from backend.modules.operations.ledger_records import (
        ACTIVE_RECOVERY_STATES,
        MIGRATION_PHASES,
    )

    if login in SCHEDULED:
        if any(item.get("operation") in SCHEDULED_OPERATIONS
               and item.get("state") in ACTIVE_RECOVERY_STATES
               for item in ledger.records("recovery-request")):
            return "scheduled-work-running"
        return None
    if login in KEYCHAIN_LOGINS:
        if any(item.get("state") in ACTIVE_RECOVERY_STATES
               for item in ledger.records("recovery-request")):
            return "recovery-under-way"
        if any(item.get("state") in MIGRATION_PHASES
               for item in ledger.records("migration-run")):
            return "migration-under-way"
    return None


# --- the evidence ------------------------------------------------------------------------------


class Evidence:
    """One line per outcome, to the root-owned audit record and then the installation
    log. A line that cannot be written never changes the answer; the answer then names
    it under `unrecorded`."""

    def __init__(self, ctx, login: str | None, actor: str | None):
        self.ctx, self.actor = ctx, actor
        self.step = login if login in HOLDERS else WORD

    def _root_record(self) -> InstallationLog:
        # No holder: a new record is the running process's (root's), 0600, in the
        # root-owned `control/`.
        return InstallationLog(self.ctx.paths.control / AUDIT_RECORD, clock=self.ctx.clock,
                               base=self.ctx.paths.prefix)

    def record(self, outcome: str, *, reason: str | None = None, count: int = 0) -> list[str]:
        fields: dict = {"count": count}
        if reason is not None:
            fields["reason"] = reason
        if self.actor is not None:
            fields["actor"] = self.actor
        unrecorded = []
        for name, log in (("password-changes", self._root_record),
                          ("installation-log", lambda: self.ctx.log)):
            try:
                log().write(PHASE, self.step, outcome, **fields)
            except (OSError, ValueError):
                unrecorded.append(name)
        return unrecorded

    def answer(self, outcome: str, value: dict, **fields) -> dict:
        unrecorded = self.record(outcome, **fields)
        return {**value, "unrecorded": unrecorded} if unrecorded else value


def _refusal_answer(evidence: Evidence, login: str | None, refused: Refused) -> dict:
    outcome = "failed" if refused.failed else "refused"
    return evidence.answer(outcome, {"ok": False, "login": login, "outcome": outcome,
                                     "reason": refused.reason}, reason=refused.reason)


# --- the change --------------------------------------------------------------------------------


def change_password(ctx, login: str, *, actor: str | None, ledger) -> dict:
    """One holder's passwords changed with its roles' verifiers (module docstring). The
    answer is `{ok, login, roles, holder, consequence}` when done, or `{ok, login,
    outcome, reason}`; it never holds a secret."""
    evidence = Evidence(ctx, login, actor)
    holder = HOLDERS.get(login)
    if holder is None:
        return _refusal_answer(evidence, None, Refused("login-outside-its-set"))
    if manifest.marker_valid(ctx.paths, ctx.clock()):
        return _refusal_answer(evidence, login, Refused("arrangement-change-in-progress"))
    manifest.begin_change(ctx.paths, REASON, clock=ctx.clock, owner_uid=ctx.root_uid)
    try:
        _precondition(ctx, holder, ledger)
        with contextlib.ExitStack() as stack:
            place = _Place.reach(ctx, holder, stack)
            _change(ctx, holder, place, evidence)
    except Refused as refused:
        return _refusal_answer(evidence, login, refused)
    finally:
        manifest.end_change(ctx.paths)
    value = {"ok": True, "login": login, "roles": list(holder.roles),
             "holder": place.name, "consequence": holder.consequence}
    return evidence.answer("done", value, count=len(holder.roles))


def _precondition(ctx, holder: Holder, ledger) -> None:
    if holder.precondition == "v2-stopped":
        _v2_stopped(ctx)
    elif holder.precondition == "scheduled-work":
        _no_work(ledger, holder.key)
    elif holder.precondition == "in-person-logins":
        from docsuri_ops.release import release_run_active

        running = release_run_active(ctx.paths)
        if running is not None:
            raise Refused(running)
        _no_work(ledger, holder.key)


def _v2_stopped(ctx) -> None:
    """Each of v2's three roles has a current, root-owned stop record, as the production
    tool's `ToolContext.v2_stopped` reads them."""
    from docsuri_ops.production_tool import V2_ROLES
    from docsuri_ops.u8_platform.fixed import read_stop_record

    now = ctx.clock()
    for label in V2_ROLES:
        record = read_stop_record(ctx.paths.control_stops / f"{label}.json",
                                  owner_uid=ctx.root_uid, now=now)
        if record is None or record["label"] != label:
            raise Refused("v2-running")


def _no_work(ledger, login: str) -> None:
    try:
        found = work_under_way(ledger, login)
    except Exception:  # noqa: BLE001 - any failure to read is an unreadable ledger
        raise Refused("ledger-unreadable") from None
    if found is not None:
        raise Refused(found)


def _change(ctx, holder: Holder, place: _Place, evidence: Evidence) -> None:
    """Steps 4 to 10, in order."""
    values = {role: ctx.generate().decode("ascii") for role in holder.roles}
    verifiers = {role: scram_sha256_verifier(value, salt=secrets.token_bytes(SALT_BYTES))
                 for role, value in values.items()}
    place.write_pending(values)
    try:
        ctx.database.run_script(alter_roles_script(holder.key, verifiers))
    except Exception:  # noqa: BLE001 - any failure leaves every role as it was
        place.remove_pending()
        raise Refused("verifier-not-set", failed=True) from None
    place.rewrite(values)
    place.read_back(values)
    for role, value in values.items():
        # A refused login answers False (`ProductionDatabase.login_check`). Whatever else it
        # raises is not a login's answer either: the role did not log in, so it is the same
        # failed `login-check-failed` refusal as a False answer (its one outcome line in each
        # record, never a secret); the marker goes in `change_password`'s `finally`.
        try:
            logged_in = ctx.database.login_check(role, value)
        except Exception:  # noqa: BLE001 - not a login's answer: the role did not log in
            raise Refused("login-check-failed", failed=True) from None
        if not logged_in:
            raise Refused("login-check-failed", failed=True)
    if holder.key == "scheduler":
        try:
            ctx.tools.restart(STANDING_JOB)
        except Exception:  # noqa: BLE001 - the change holds; the restart is repeated
            raise Refused("standing-restart-failed", failed=True) from None


class _Place:
    """Where one holder keeps its passwords: a file reached through its folder's
    descriptor (kept open for the whole change), or a System keychain item."""

    def __init__(self, ctx, holder: Holder, folder: int | None, path: Path | None,
                 document: dict | None):
        self.ctx, self.holder, self.folder, self.path = ctx, holder, folder, path
        self.document = document

    @property
    def name(self) -> str:
        if self.path is None:
            return keychain.LOGIN_ITEMS[str(self.holder.location)]
        return str(self.path.relative_to(self.ctx.paths.prefix))

    @property
    def pending(self) -> str:
        return self.path.name + PENDING_SUFFIX

    @classmethod
    def reach(cls, ctx, holder: Holder, stack: contextlib.ExitStack) -> _Place:
        """Step 3: the holder in place, else `holder-missing` or `holder-refused`."""
        if holder.kind == "keychain":
            if not keychain.present(ctx.tools, str(holder.location)):
                raise Refused("holder-missing")
            return cls(ctx, holder, None, None, None)
        path = holder.location(ctx.paths)
        try:
            folder = stack.enter_context(safe_fs.folder_at(ctx.paths.prefix, path.parent))
            raw = _read_holder(ctx, folder, path.name, ctx.uid(holder.account))
        except FileNotFoundError:
            raise Refused("holder-missing") from None
        except (OSError, ValueError):
            raise Refused("holder-refused") from None
        document = _parsed(holder, raw)
        return cls(ctx, holder, folder, path, document)

    def _content(self, values: dict[str, str]) -> bytes:
        if self.holder.kind == "raw":
            return values[self.holder.roles[0]].encode("ascii")
        document = copy.deepcopy(self.document)
        for role, field in zip(self.holder.roles, self.holder.fields, strict=True):
            _set_field(document, field, values[role])
        return json.dumps(document, sort_keys=True).encode()

    def write_pending(self, values: dict[str, str]) -> None:
        """Step 5: a new pending file beside the holder, 0600, given to its account on its
        own descriptor."""
        if self.path is None:
            return
        uid, gid = self.ctx.uid(self.holder.account), self.ctx.gid(self.holder.account)
        try:
            safe_fs.remove(self.folder, self.pending)
            safe_fs.create_file(self.folder, self.pending, self._content(values), mode=0o600,
                                give=lambda descriptor: self.ctx.tools.fchown(descriptor,
                                                                              uid, gid))
        except OSError:
            raise Refused("holder-refused") from None

    def remove_pending(self) -> None:
        if self.path is not None:
            with contextlib.suppress(OSError):
                safe_fs.remove(self.folder, self.pending)

    def rewrite(self, values: dict[str, str]) -> None:
        """Step 7: the pending name renamed over the holder, or the keychain item
        replaced."""
        try:
            if self.path is None:
                keychain.store_login(self.ctx.tools, str(self.holder.location),
                                     values[self.holder.roles[0]].encode("ascii"))
            else:
                safe_fs.replace(self.folder, self.pending, self.path.name)
        except Exception:  # noqa: BLE001 - the holder keeps its old passwords
            self.remove_pending()
            raise Refused("holder-not-rewritten", failed=True) from None

    def read_back(self, values: dict[str, str]) -> None:
        """Step 8: the holder read back as root and compared with the new values."""
        try:
            same = self._keychain_same(values) if self.path is None else self._file_same(values)
        except Exception:  # noqa: BLE001 - a holder that cannot be read back is not rewritten
            same = False
        if not same:
            raise Refused("holder-not-rewritten", failed=True)

    def _keychain_same(self, values: dict[str, str]) -> bool:
        item = keychain.LOGIN_ITEMS[str(self.holder.location)]
        held = self.ctx.tools.keychain_read(item)
        try:
            return hmac.compare_digest(bytes(held), values[self.holder.roles[0]].encode("ascii"))
        finally:
            held[:] = b"\0" * len(held)

    def _file_same(self, values: dict[str, str]) -> bool:
        raw = _read_holder(self.ctx, self.folder, self.path.name,
                           self.ctx.uid(self.holder.account))
        if self.holder.kind == "raw":
            return hmac.compare_digest(raw, values[self.holder.roles[0]].encode("ascii"))
        document = json.loads(raw)
        return all(hmac.compare_digest(str(_field(document, field)).encode(),
                                       values[role].encode("ascii"))
                   for role, field in zip(self.holder.roles, self.holder.fields, strict=True))


def _read_holder(ctx, folder: int, name: str, account_uid: int) -> bytes:
    """A holder file's bytes: a regular file with one name, at 0600, owned by its
    account (read through the tools, as the installer reads a log's owner)."""
    descriptor = safe_fs.open_existing(folder, name)
    try:
        info = os.fstat(descriptor)
        if stat.S_IMODE(info.st_mode) != 0o600 or (
                ctx.tools.descriptor_owner(descriptor) != account_uid):
            raise safe_fs.PathRefused(safe_fs.NOT_ITS_OWN_FILE)
        raw = safe_fs.read_all(descriptor, MAX_HOLDER)
    finally:
        os.close(descriptor)
    if len(raw) > MAX_HOLDER:
        raise ValueError("holder too large")
    return raw


def _parsed(holder: Holder, raw: bytes) -> dict | None:
    """The holder's document, each named field holding 64 hexadecimal characters."""
    if holder.kind == "raw":
        if not _SECRET.fullmatch(raw.decode("ascii", "replace")):
            raise Refused("holder-refused")
        return None
    try:
        document = json.loads(raw)
        held = [_field(document, field) for field in holder.fields]
    except (ValueError, KeyError, TypeError):
        raise Refused("holder-refused") from None
    if not isinstance(document, dict) or not all(
            isinstance(value, str) and _SECRET.fullmatch(value) for value in held):
        raise Refused("holder-refused")
    return document


def _field(document, field: tuple[str, ...]):
    value = document
    for name in field:
        value = value[name]
    return value


def _set_field(document: dict, field: tuple[str, ...], value: str) -> None:
    target = document
    for name in field[:-1]:
        target = target[name]
    target[field[-1]] = value


# --- the word ----------------------------------------------------------------------------------


def _read_input(stdin) -> str:
    raw = stdin.read(MAX_INPUT + 1)
    if len(raw) > MAX_INPUT:
        raise Refused("input-too-large")
    try:
        value = json.loads(raw)
    except (ValueError, UnicodeDecodeError, RecursionError):
        raise Refused("input-not-json") from None
    if not isinstance(value, dict):
        raise Refused("input-not-an-object")
    if set(value) != {"login"} or not isinstance(value["login"], str):
        raise Refused("input-field-refused")
    return value["login"]


def run_change_password(stdin, environ, *, paths: ArrangementPaths, context,
                        ledger) -> tuple[dict, int]:
    """The word after `main`'s root check: exactly `{"login": <key>}` on standard input
    (at most 4 KiB), the actor the account sudo authenticated (`in_person_actor`, which
    must be the installed operator), then `change_password`. Exit 0 when done, else 1."""
    from docsuri_ops.production_wiring import WiringRefused, in_person_actor

    try:
        login = _read_input(stdin)
    except Refused as refused:
        return _refusal_answer(Evidence(context, None, None), None, refused), 1
    try:
        actor = in_person_actor(paths, environ, owner_uid=context.root_uid)
    except WiringRefused as refused:
        answer = _refusal_answer(Evidence(context, login, None), login, Refused(str(refused)))
        return answer, 1
    result = change_password(context, login, actor=actor, ledger=ledger)
    return result, 0 if result.get("ok") else 1
