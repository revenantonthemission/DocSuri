import { test, expect } from '@playwright/test';
import { clearProtectedContext } from './helpers';
test.afterEach(async ({ page }) => clearProtectedContext(page));
import { fixtures, login, openControls, verifyLink, totp } from './helpers';
test.describe.configure({ mode: 'serial' });
test('registration, delivered verification, and one-time local MFA enrollment', async ({
  page,
}) => {
  const account = fixtures().accounts.registration;
  await page.goto('/');
  await page.getByTestId('entry-switch').click();
  await page.getByLabel('이메일', { exact: true }).fill(account.email);
  await page.getByLabel('비밀번호', { exact: true }).fill(account.password);
  await page.getByTestId('entry-submit').click();
  await expect(page.getByText(/대상과 조건이 맞으면/)).toBeVisible();
  await verifyLink(page, 'registration', 'verify');
  await page.getByTestId('entry-submit').click();
  await expect(page.getByText(/인증 요청을 확인했어요/)).toBeVisible();
  await login(page, account);
  await openControls(page, 'account');
  await page.getByText('추가 인증(MFA)', { exact: true }).click();
  await page.getByLabel('MFA 설정용 현재 비밀번호').fill(account.password);
  await page.getByRole('button', { name: '새 MFA 등록 준비' }).click();
  await page.getByRole('button', { name: '설정 키 한 번 보기' }).waitFor();
  await page.getByLabel('MFA 설정용 현재 비밀번호').fill(account.password);
  await page.getByRole('button', { name: '설정 키 한 번 보기' }).click();
  const seed = await page.locator('.protected-material > code').textContent();
  if (!seed) throw new Error('one-time material absent');
  await expect(page.getByRole('img', { name: '인증 앱에서 스캔할 일회성 QR 코드' })).toBeVisible();
  await page.getByRole('button', { name: '설정 자료 숨기기' }).click();
  expect(await page.locator('.protected-material').count()).toBe(0);
  await page.getByLabel('등록 확인 코드').fill(totp(seed));
  await page.getByRole('button', { name: 'MFA 등록 확인' }).click();
  await expect(page.getByText('요청 결과를 확인했어요').last()).toBeVisible();
  await page.getByTestId('logout').click();
  await page.getByLabel('이메일', { exact: true }).fill(account.email);
  await page.getByLabel('비밀번호', { exact: true }).fill(account.password);
  await page.getByTestId('entry-submit').click();
  await page.getByLabel('인증 앱 코드').fill(totp(seed, 1));
  await page.getByTestId('entry-submit').click();
  await expect(page.getByTestId('logout')).toBeVisible();
});
test('password reset, fresh authentication and credential replacement', async ({ page }) => {
  const account = fixtures().accounts.memberB;
  const replacement = 'Different!Research2026';
  await page.goto('/');
  await page.getByRole('button', { name: '비밀번호를 잊었나요?' }).click();
  await page.getByLabel('이메일', { exact: true }).fill(account.email);
  await page.getByTestId('entry-submit').click();
  await expect(page.getByText(/대상과 조건이 맞으면/)).toBeVisible();
  await verifyLink(page, 'memberB', 'password-reset');
  await page.getByLabel('새 비밀번호', { exact: true }).fill(replacement);
  await page.getByTestId('entry-submit').click();
  await expect(page.getByText(/인증 요청을 확인했어요/)).toBeVisible();
  await login(page, { ...account, password: replacement });
  await openControls(page, 'account');
  await page.getByText('비밀번호와 이메일', { exact: true }).click();
  await page.getByLabel('현재 비밀번호', { exact: true }).fill(replacement);
  await page.getByLabel('새 비밀번호', { exact: true }).fill(account.password);
  await page.getByRole('button', { name: '비밀번호 변경 후 다시 로그인' }).click();
  await expect(page.getByTestId('entry-panel')).toBeVisible();
  await login(page, account);
});
test('local identity links are labelled fixtures and can be removed', async ({ page }) => {
  await login(page, fixtures().accounts.memberA);
  await openControls(page, 'account');
  await page.getByText('Google · ORCID 연결', { exact: true }).click();
  await expect(page.getByText(/실제 Google·ORCID 연결은 아직/)).toBeVisible();
  await page.getByRole('button', { name: 'orcid 시험 연결' }).click();
  await page.getByRole('button', { name: 'ORCID 자료 확인' }).waitFor();
  await page.getByRole('button', { name: 'ORCID 자료 확인' }).click();
  await expect(page.getByText(/ORCID 시험 자료 범위/)).toBeVisible();
  await page.getByRole('button', { name: '연결 해제', exact: true }).click();
  await expect(page.getByRole('button', { name: 'ORCID 자료 확인' })).toHaveCount(0);
});
